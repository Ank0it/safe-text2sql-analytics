"""
Generate a Markdown benchmark report from benchmark_report.json.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent

REPORT_JSON = ROOT_DIR / "benchmark" / "benchmark_report.json"
REPORT_MD = ROOT_DIR / "benchmark" / "benchmark_report.md"


def generate_markdown_report() -> None:
    """
    Generate a Markdown report from the benchmark JSON output.
    """

    if not REPORT_JSON.exists():
        raise FileNotFoundError(
            f"Benchmark report not found:\n{REPORT_JSON}"
        )

    with open(REPORT_JSON, "r", encoding="utf-8") as file:
        report = json.load(file)

    summary = report.get("summary", {})
    metadata = report.get("metadata", {})
    results = report.get("results", [])

    lines = []

    lines.append("# Safe Text2SQL Analytics Benchmark Report\n")

    if metadata:
        lines.append("## Benchmark Metadata\n")
        lines.append(
            f"- **Generated At:** {metadata.get('generated_at', 'N/A')}"
        )
        lines.append(
            f"- **Benchmark Version:** {metadata.get('benchmark_version', 'N/A')}"
        )
        lines.append(
            f"- **Total Runtime:** {metadata.get('total_runtime_seconds', 'N/A')} seconds\n"
        )

    lines.append("## Summary\n")

    lines.append(
        f"- **Questions:** {summary.get('questions', summary.get('total_questions', 0))}"
    )
    lines.append(
        f"- **Passed:** {summary.get('passed', 0)}"
    )
    lines.append(
        f"- **Failed:** {summary.get('failed', 0)}"
    )
    lines.append(
        f"- **Intent Accuracy:** {summary.get('intent_accuracy', 0):.2f}%"
    )
    lines.append(
        f"- **Unsafe Query Block Rate:** {summary.get('unsafe_query_block_rate', 0):.2f}%\n"
    )

    lines.append("## Detailed Results\n")

    lines.append(
        "| ID | Status | Safe | Latency (ms) | Validation | Question |"
    )
    lines.append(
        "|----|--------|------|--------------|------------|----------|"
    )

    for result in results:

        status = "PASS" if result.get("passed") else "FAIL"

        safe = (
            "Safe"
            if result.get("expected_safe", False)
            else "Unsafe"
        )

        latency = result.get("latency_ms", "-")

        validation = result.get(
            "validation_reason",
            "",
        ).replace("\n", " ")

        question = result.get("question", "")

        lines.append(
            f"| {result.get('id')} | "
            f"{status} | "
            f"{safe} | "
            f"{latency} | "
            f"{validation} | "
            f"{question} |"
        )

    lines.append("\n---\n")
    lines.append(
        "Report automatically generated by the benchmark pipeline."
    )

    with open(REPORT_MD, "w", encoding="utf-8") as file:
        file.write("\n".join(lines))

    print("=" * 80)
    print("Markdown benchmark report generated successfully.")
    print(f"Saved to: {REPORT_MD}")
    print("=" * 80)


if __name__ == "__main__":
    generate_markdown_report()